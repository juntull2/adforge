def make_selectbox_options(cn_list: list, category: str):
    """
    (한국어 표시명, 중국어 enum 이름) 튜플 리스트 반환.
    ⭐ 추천 항목이 맨 앞, 나머지는 가나다 순.
    """
    mapping = {"intro": INTRO_KO, "loop": LOOP_KO, "outro": OUTRO_KO}
    d = mapping.get(category, {})

    recommended = []
    others = []
    for cn in cn_list:
        ko = d.get(cn, cn)
        if ko.startswith("⭐"):
            recommended.append((ko, cn))
        else:
            others.append((ko, cn))

    others.sort(key=lambda x: x[0])
    return [("(없음)", None)] + recommended + others
